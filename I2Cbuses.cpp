#include "I2CBuses.h"
#include "Config.h"

// ============================================================
// DEFINE I2C BUS OBJECTS
// ============================================================

TwoWire I2C_Right = Wire;

TwoWire I2C_Left = TwoWire(1);


// ============================================================
// INITIALIZE I2C
// ============================================================

void initI2CBuses()
{
    // --------------------------------------------------------
    // Bus 0
    // Right AS5600 + VL53L0X
    // --------------------------------------------------------

    Wire.begin(RIGHT_SDA, RIGHT_SCL, 400000);


    // --------------------------------------------------------
    // Bus 1
    // Left AS5600 + MPU9250
    // --------------------------------------------------------

    I2C_Left.begin(LEFT_SDA, LEFT_SCL, 400000);
}